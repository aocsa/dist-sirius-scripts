#!/usr/bin/env bash
# Benchmarks queries over scale factors and GPU counts, checks every run's answer against
# expected/<query>_sf<SF>.csv when there is one, and writes results.csv.
#   scripts/bench.sh
#
#   QUERIES     files in sql/ without .sql            (default "q5 q5_theseus")
#   SFS         scale factors                         (default 1000)
#   GPU_COUNTS  1 runs one process (no exchange); N>1 runs N ranks   (default "1 2")
#   RUNS        runs per process; the first is cold when COLD=1     (default 3)
#   COLD        1: drop the page cache and empty the spill dir before each process (default 1)
#   CONFIG      Sirius YAML; default: one generated by make_config.sh from the environment
# Output: $OUT/bench-<timestamp>/{results.csv, <query>-sf<SF>-<N>gpu/...}. The answer column is
# explained in tools/check_runs.py (ok, WRONG, ERROR, MISSING, n/a, EMPTY, +RANK_FAILED).
# Exits non-zero if any run is not ok / n/a.
set -uo pipefail
source "$(dirname "$0")/common.sh"

: "${QUERIES:=q5 q5_theseus}"
: "${SFS:=1000}"
: "${GPU_COUNTS:=1 2}"
: "${RUNS:=3}"
: "${COLD:=1}"
dir="$OUT/bench-$(date +%Y%m%d-%H%M%S)"
mkdir -p "$dir"
if [ -z "${CONFIG:-}" ]; then
  CONFIG="$dir/sirius.yaml"
  "$REPO_DIR/scripts/make_config.sh" "$CONFIG" > /dev/null || die "make_config.sh failed"
fi
export CONFIG
cp "$CONFIG" "$dir/sirius.yaml" 2>/dev/null || true
results="$dir/results.csv"
echo "query,sf,gpus,run,seconds,answer" > "$results"
status=0

for sf in $SFS; do
  data="$DATA_ROOT/tpch_parquet_sf$sf"
  [ -d "$data/lineitem" ] || die "no data at $data (scripts/gen_tpch.sh $sf)"
  for q in $QUERIES; do
    [ -f "$REPO_DIR/sql/$q.sql" ] || die "no sql/$q.sql"
    sql="$dir/$q-sf$sf.sql"
    {
      sed "s|@DATA@|$data|g" "$REPO_DIR/sql/views.sql"
      # Marks the end of the setup statements for tools/check_runs.py.
      echo ".print BENCH_START"
      echo ".timer on"
      for ((r = 0; r < RUNS; r++)); do grep -v '^--' "$REPO_DIR/sql/$q.sql"; done
    } > "$sql"
    for n in $GPU_COUNTS; do
      run="$dir/$q-sf$sf-${n}gpu"
      echo "== $q SF$sf on $n GPU(s)"
      if [ "$COLD" = 1 ]; then
        drop_page_cache
        # Only a directory make_config.sh set up as a spill tier is emptied.
        if [ -f "$SPILL_DIR/$SPILL_MARKER" ]; then
          find "$SPILL_DIR" -mindepth 1 ! -name "$SPILL_MARKER" -delete
        fi
      fi
      if [ "$n" = 1 ]; then
        "$REPO_DIR/scripts/run_single.sh" "$sql" "$run" > /dev/null
        rc=$?
        out="$run/out.log"
      else
        "$REPO_DIR/scripts/run_ranks.sh" "$n" "$sql" "$run" > /dev/null
        rc=$?
        out="$run/rank0/out.log"
      fi
      rows=$(python3 "$REPO_DIR/tools/check_runs.py" "$out" \
        "$REPO_DIR/expected/${q%_theseus}_sf$sf.csv" "$q" "$sf" "$n" "$RUNS" "$rc")
      echo "$rows" >> "$results"
      echo "$rows" | sed 's/^/   /'
      echo "$rows" | grep -qvE ',(ok|n/a)$' && status=1
    done
  done
done
echo "results: $results"
exit $status
